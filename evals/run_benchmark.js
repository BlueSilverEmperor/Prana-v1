/**
 * Automated Evaluation Harness & Benchmark Suite (Features #23 & #24).
 * Runs the Python 55-scenario benchmark and writes evals/benchmark_summary.md from its JSON
 * output (4 baselines, 95% Wilson confidence intervals). No metric is hardcoded here.
 */

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { spawn } from "child_process";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const REPO_ROOT = path.resolve(__dirname, "..");

// Wilson score interval for binomial proportions
function wilsonInterval(k, n, z = 1.96) {
  if (n === 0) return [0, 0];
  const p = k / n;
  const denominator = 1 + (z * z) / n;
  const centre = (p + (z * z) / (2 * n)) / denominator;
  const spread = (z * Math.sqrt((p * (1 - p)) / n + (z * z) / (4 * n * n))) / denominator;
  return [Math.max(0, centre - spread), Math.min(1, centre + spread)];
}

function formatRate(k, n) {
  const pct = n > 0 ? ((k / n) * 100).toFixed(1) : "0.0";
  const [lo, hi] = wilsonInterval(k, n);
  return `${k}/${n} (${pct}%, CI ${(lo * 100).toFixed(1)}%–${(hi * 100).toFixed(1)}%)`;
}

const TIME_BUDGET_S = 15;
const BASELINE_LABELS = {
  "plain-wallet": "Plain Wallet",
  "static-blocklist": "Static Blocklist",
  "warnings-only": "Warnings Only",
  "full-vero": "Full Vero",
};

// Try interpreters in order: $PYTHON, the repo venv, python3, python (macOS ships only python3).
function pythonCandidates() {
  const venv = path.join(REPO_ROOT, ".venv", "bin", "python");
  return [process.env.PYTHON, fs.existsSync(venv) ? venv : null, "python3", "python"].filter(Boolean);
}

function runWith(cmd) {
  return new Promise((resolve, reject) => {
    const py = spawn(cmd, ["-m", "simulator.bench.run_eval"], { cwd: REPO_ROOT, stdio: "pipe" });
    let stdout = "";
    let stderr = "";
    py.stdout.on("data", (d) => { stdout += d.toString(); });
    py.stderr.on("data", (d) => { stderr += d.toString(); });
    py.on("error", (err) => reject(Object.assign(err, { notFound: err.code === "ENOENT" })));
    py.on("close", (code) => (code === 0 ? resolve(stdout)
      : reject(new Error(`${cmd} -m simulator.bench.run_eval exited ${code}: ${stderr.trim()}`))));
  });
}

async function runPythonBenchmark() {
  for (const cmd of pythonCandidates()) {
    try {
      return await runWith(cmd);
    } catch (err) {
      if (!err.notFound) throw err;
    }
  }
  throw new Error("No Python interpreter found (set $PYTHON or create .venv)");
}

function rateFromRow(rate) {
  return formatRate(rate.successes, rate.trials);
}

// Every number in the summary comes from simulator/bench/results/benchmark.json.
function renderSummary(bench, elapsed) {
  const m = bench.metrics;
  const rows = bench.baselines.map((b) =>
    `| ${BASELINE_LABELS[b.name] || b.name} | ${rateFromRow(b.detection)} | ${rateFromRow(b.block)} | ${rateFromRow(b.false_positive)} |`);
  const attr = bench.ruleAttribution;
  return `# Project Vero — Benchmark Results (${m.totalScenarios} scenarios, ${bench.mode} mode)

Generated by \`node evals/run_benchmark.js\` from \`simulator/bench/results/benchmark.json\`.
Run time ${elapsed.toFixed(2)}s (budget ${TIME_BUDGET_S}s). Engine latency p50 ${m.p50LatencyMs} ms, p95 ${m.p95LatencyMs} ms.
Expected-rule attribution on malicious scenarios: ${formatRate(attr.successes, attr.trials)}.

| Baseline | Detection | Block | False positives |
| :--- | :--- | :--- | :--- |
${rows.join("\n")}

Caveats: scenarios are team-authored (held-out set still needs an outside author); the Full Vero block
rate is modelled from HIGH/CRITICAL verdicts, not measured on-chain; static mode predicts effects from calldata.
`;
}

async function main() {
  const startTime = Date.now();
  console.log("PROJECT VERO: benchmark harness (wraps python -m simulator.bench.run_eval)\n");
  const pyOutput = await runPythonBenchmark();
  const elapsed = (Date.now() - startTime) / 1000;
  console.log(pyOutput);

  const resultsJsonPath = path.join(REPO_ROOT, "simulator", "bench", "results", "benchmark.json");
  if (!fs.existsSync(resultsJsonPath)) {
    throw new Error(`Expected results at ${resultsJsonPath}, but the benchmark did not write them`);
  }
  const bench = JSON.parse(fs.readFileSync(resultsJsonPath, "utf-8"));
  const outMdPath = path.join(REPO_ROOT, "evals", "benchmark_summary.md");
  fs.writeFileSync(outMdPath, renderSummary(bench, elapsed));
  console.log(`Summary written to ${outMdPath}`);
  const withinBudget = elapsed < TIME_BUDGET_S;
  console.log(`Run time ${elapsed.toFixed(2)}s: ${withinBudget ? "within" : "OVER"} the ${TIME_BUDGET_S}s budget`);
  if (!withinBudget) process.exitCode = 1;
}

main().catch((err) => {
  console.error("Evaluation failed:", err);
  process.exit(1);
});
